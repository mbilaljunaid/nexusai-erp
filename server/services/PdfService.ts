
import PDFDocument from "pdfkit";
import { format } from "date-fns";

export class PdfService {

    static async generatePayslip(stream: any, data: {
        employeeName: string;
        employeeId: string;
        payPeriod: string;
        paymentDate: string;
        earnings: any[];
        deductions: any[];
        netPay: number;
    }) {
        const doc = new PDFDocument({ margin: 50 });
        doc.pipe(stream);

        // --- HEADER ---
        doc.fontSize(20).text("NEXUS ERP", { align: "center" });
        doc.fontSize(10).text("Workforce Rewards Module", { align: "center" });
        doc.moveDown();
        doc.moveDown();

        // --- TITLE ---
        doc.fontSize(16).text("PAYSLIP STATEMENT", { align: "left", underline: true });
        doc.moveDown();

        // --- EMPLOYEE INFO TABLE ---
        const startY = doc.y;
        doc.fontSize(10);

        doc.text(`Employee: ${data.employeeName}`, 50, startY);
        doc.text(`Employee ID: ${data.employeeId}`, 300, startY);
        doc.moveDown();

        doc.text(`Pay Period: ${data.payPeriod}`, 50);
        doc.text(`Payment Date: ${format(new Date(data.paymentDate), "MMM dd, yyyy")}`, 300);

        doc.moveDown();
        doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke(); // Separator Line
        doc.moveDown();

        // --- EARNINGS & DEDUCTIONS HEADERS ---
        const tableTop = doc.y;
        doc.font("Helvetica-Bold");
        doc.text("EARNINGS", 50, tableTop);
        doc.text("AMOUNT", 200, tableTop, { align: "right" });

        doc.text("DEDUCTIONS", 300, tableTop);
        doc.text("AMOUNT", 500, tableTop, { align: "right" });
        doc.font("Helvetica");
        doc.moveDown();

        // --- DETAILS ---
        const earningsY = doc.y;
        let currentY = earningsY;

        // Earnings List
        data.earnings.forEach(e => {
            doc.text(e.elementName, 50, currentY);
            doc.text(Number(e.amount).toFixed(2), 200 - 50, currentY, { align: "right", width: 50 });
            currentY += 15;
        });

        // Deductions List
        let dedY = earningsY;
        data.deductions.forEach(d => {
            doc.text(d.elementName, 300, dedY);
            doc.text(Math.abs(Number(d.amount)).toFixed(2), 500 - 50, dedY, { align: "right", width: 50 });
            dedY += 15;
        });

        // Reset Y to max
        doc.y = Math.max(currentY, dedY) + 20;

        // --- TOTALS ---
        doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
        doc.moveDown();

        const totalEarnings = data.earnings.reduce((a, b) => a + Number(b.amount), 0);
        const totalDeductions = data.deductions.reduce((a, b) => a + Math.abs(Number(b.amount)), 0);

        doc.font("Helvetica-Bold");
        doc.text("TOTAL GROSS PAY", 50, doc.y);
        doc.text(totalEarnings.toFixed(2), 200 - 50, doc.y, { align: "right", width: 50 });

        doc.text("TOTAL DEDUCTIONS", 300, doc.y); // Same line
        doc.text(totalDeductions.toFixed(2), 500 - 50, doc.y, { align: "right", width: 50 }); // Align right

        doc.moveDown(2);

        // --- NET PAY HERO ---
        doc.rect(50, doc.y, 500, 40).fillAndStroke("#f0fdf4", "#166534");
        doc.fillColor("#166534").fontSize(14).text("NET PAY DISTRIBUTED", 70, doc.y + 12);
        doc.text("$" + data.netPay.toFixed(2), 400, doc.y + 12, { align: "right" });

        doc.fillColor("black"); // Reset text color

        // --- FOOTER ---
        doc.fontSize(8).text("Generated by NexusAI ERP - Confidential", 50, 700, { align: "center", width: 500 });

        doc.end();
    }
}
