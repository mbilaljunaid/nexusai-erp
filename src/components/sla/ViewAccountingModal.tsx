import { formatDate } from "@/lib/dateUtils";

import {
    Dialog, DialogContent, DialogHeader, DialogTitle, DialogDescription
} from "@/components/ui/dialog";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Badge } from "@/components/ui/badge";
import { useQuery } from "@tanstack/react-query";
import { Loader2 } from "lucide-react";
import { formatCurrency } from "@/lib/utils";
import { Button } from "@/components/ui/button";
import { AccountingTraceModal } from "@/components/finance/sla/AccountingTraceModal";
import { useState } from "react";
import { BrainCircuit } from "lucide-react";

interface ViewAccountingModalProps {
    entityId: string | null;
    open: boolean;
    onOpenChange: (open: boolean) => void;
}

export function ViewAccountingModal({ entityId, open, onOpenChange }: ViewAccountingModalProps) {
    const { data: accounting, isLoading } = useQuery({
        queryKey: ["/api/sla/accounting", entityId],
        queryFn: async () => {
            if (!entityId) return null;
            const res = await fetch(`/api/sla/accounting/${entityId}`);
            return res.json();
        },
        enabled: !!entityId && open
    });

    const [showTrace, setShowTrace] = useState(false);
    const [traceData, setTraceData] = useState<any>(null);
    const [isTraceLoading, setIsTraceLoading] = useState(false);

    const handleExplain = async () => {
        setIsTraceLoading(true);
        setShowTrace(true);
        try {
            // Need to construct payload. 
            // Since we have entityId, and assuming entityTable from Header or context.
            // Wait, "accounting" response includes "entityTable".
            if (!accounting?.entityTable) {
                // Determine table based on ID or source? 
                // Currently fetching by header.entityId. Header includes entityTable.
                // Uh oh, getAccounting returns Header which HAS entityTable.
            }

            const res = await fetch("/api/sla/explain", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    entityId: entityId,
                    entityTable: accounting?.entityTable || "ap_invoices", // Fallback for MVP
                    eventClassId: accounting?.eventClassId,
                    eventTypeId: accounting?.eventTypeId,
                    ledgerId: accounting?.ledgerId
                })
            });
            const data = await res.json();
            setTraceData(data);
        } catch (error) {
        } finally {
            setIsTraceLoading(false);
        }
    };

    const isMissing = accounting?.found === false;

    return (
        <Dialog open={open} onOpenChange={onOpenChange}>
            <DialogContent className="max-w-4xl">
                <DialogHeader>
                    <DialogTitle>Subledger Accounting Impact</DialogTitle>
                    <DialogDescription>
                        Journal Entry generated by Nexus SLA Engine.
                    </DialogDescription>
                </DialogHeader>

                {/* Explain AI Modal */}
                <AccountingTraceModal
                    open={showTrace}
                    onOpenChange={setShowTrace}
                    trace={traceData}
                    isLoading={isTraceLoading}
                />

                {isLoading ? (
                    <div className="flex justify-center p-8"><Loader2 className="animate-spin" /></div>
                ) : isMissing ? (
                    <div className="p-8 text-center text-muted-foreground">
                        No accounting has been generated for this transaction yet.
                        <br /><span className="text-xs">This may be because it is still in Draft or requires validation.</span>
                    </div>
                ) : (
                    <div className="space-y-6">
                        {/* Header Info */}
                        <div className="flex justify-between items-center bg-muted/30 p-4 rounded-md border">
                            <div className="space-y-1">
                                <div className="text-sm font-medium">Event</div>
                                <div className="text-xs text-muted-foreground">{accounting?.eventClassId} / {accounting?.eventTypeId}</div>
                            </div>
                            <div className="space-y-1">
                                <div className="text-sm font-medium">Status</div>
                                <Badge variant={accounting?.status === 'Final' ? 'default' : 'secondary'}>{accounting?.status}</Badge>
                            </div>
                            <div className="space-y-1 text-right">
                                <div className="text-sm font-medium">GL Date</div>
                                <div className="text-xs text-muted-foreground">{accounting?.glDate ? formatDate(accounting.glDate) : 'N/A'}</div>
                            </div>
                            <div>
                                <Button variant="outline" size="sm" onClick={handleExplain} className="gap-2">
                                    <BrainCircuit className="h-4 w-4" /> Explain
                                </Button>
                            </div>
                        </div>

                        {/* Lines Table */}
                        <div className="border rounded-md">
                            <Table>
                                <TableHeader>
                                    <TableRow>
                                        <TableHead>Line</TableHead>
                                        <TableHead>Account / Description</TableHead>
                                        <TableHead>Class</TableHead>
                                        <TableHead className="text-right">Debit</TableHead>
                                        <TableHead className="text-right">Credit</TableHead>
                                    </TableRow>
                                </TableHeader>
                                <TableBody>
                                    {accounting?.lines?.map((line: any) => (
                                        <TableRow key={line.id}>
                                            <TableCell className="font-mono text-xs">{line.lineNumber}</TableCell>
                                            <TableCell>
                                                <div className="font-medium text-sm">{line.codeCombination?.accountType} {line.codeCombination?.codeString}</div>
                                                <div className="text-xs text-muted-foreground">{line.description}</div>
                                            </TableCell>
                                            <TableCell><Badge variant="outline">{line.accountingClass}</Badge></TableCell>
                                            <TableCell className="text-right font-mono">
                                                {line.accountedDr ? formatCurrency(line.accountedDr, accounting.currencyCode) : '-'}
                                            </TableCell>
                                            <TableCell className="text-right font-mono">
                                                {line.accountedCr ? formatCurrency(line.accountedCr, accounting.currencyCode) : '-'}
                                            </TableCell>
                                        </TableRow>
                                    ))}
                                    {/* Total */}
                                    <TableRow className="bg-muted/50 font-bold">
                                        <TableCell colSpan={3} className="text-right">Total</TableCell>
                                        <TableCell className="text-right font-mono">{formatCurrency(
                                            accounting?.lines?.reduce((sum: number, l: any) => sum + Number(l.accountedDr || 0), 0),
                                            accounting?.currencyCode
                                        )}</TableCell>
                                        <TableCell className="text-right font-mono">{formatCurrency(
                                            accounting?.lines?.reduce((sum: number, l: any) => sum + Number(l.accountedCr || 0), 0),
                                            accounting?.currencyCode
                                        )}</TableCell>
                                    </TableRow>
                                </TableBody>
                            </Table>
                        </div>
                    </div>
                )}
            </DialogContent>
        </Dialog>
    );
}
