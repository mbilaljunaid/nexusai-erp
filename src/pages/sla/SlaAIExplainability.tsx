import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { StandardPage } from "@/components/layout/StandardPage";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Sparkles, Search, History, Eye, CheckCircle2, AlertCircle, Loader2, ArrowRight } from "lucide-react";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import { AccountingTraceModal } from "@/components/finance/sla/AccountingTraceModal";
import { format } from "date-fns";
import { useToast } from "@/hooks/use-toast";

export default function SlaAIExplainability() {
    const [searchQuery, setSearchQuery] = useState("");
    const [selectedTrace, setSelectedTrace] = useState<{ entityId: string, entityTable: string } | null>(null);
    const [selectedTraceData, setSelectedTraceData] = useState<any>(null);
    const [isTraceLoading, setIsTraceLoading] = useState(false);
    const { toast } = useToast();

    // Fetch recent explanations
    const { data: recentTraces = [], isLoading } = useQuery<any>({
        queryKey: ["sla-recent-traces"],
        queryFn: async () => {
            // Mock data for recent AI explanations
            return [
                { id: "TRC-001", entityId: "INV-2024-001", entityTable: "AP_INVOICES", date: new Date().toISOString(), status: "SUCCESS", confidence: 0.98, summary: "Item expense correctly derived via Mapping Set 'DEPT_PROJ'." },
                { id: "TRC-002", entityId: "PAY-9921", entityTable: "AP_PAYMENTS", date: new Date(Date.now() - 3600000).toISOString(), status: "SUCCESS", confidence: 0.95, summary: "Cash clearing account determined from Bank account metadata." },
                { id: "TRC-003", entityId: "INV-2024-005", entityTable: "AP_INVOICES", date: new Date(Date.now() - 86400000).toISOString(), status: "WARNING", confidence: 0.72, summary: "Fallback account used due to missing Mapping Set entry for Department 'R&D'." },
            ];
        }
    });

    // Fetch Proactive Insights
    const { data: insights = [], refetch: refetchInsights } = useQuery<any>({
        queryKey: ["sla-insights"],
        queryFn: async () => {
            const res = await fetch("/api/sla/insights");
            return res.json();
        }
    });

    const handleApplyInsight = (insight: any) => {
        toast({
            title: "Suggestion Applied",
            description: `Auto-optimizing rule context for ${insight.title}.`,
            variant: "default"
        });
        // In a real implementation, this would trigger a PATCH to the rule configuration
    };

    const handleViewTrace = async (traceInfo: { entityId: string, entityTable: string }) => {
        setSelectedTrace(traceInfo);
        setIsTraceLoading(true);
        try {
            const res = await fetch("/api/sla/explain", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify(traceInfo)
            });
            const data = await res.json();
            setSelectedTraceData(data);
        } catch (e) {
            console.error("Failed to fetch trace", e);
        } finally {
            setIsTraceLoading(false);
        }
    };

    return (
        <StandardPage
            title="AI Accounting Intelligence"
            description="Trace and understand the logic behind every accounting entry generated by the SLA engine."
            breadcrumbs={[{ label: "Finance", href: "/finance" }, { label: "SLA Intelligence" }]}
        >
            <div className="flex flex-col gap-8">
                {/* Stats Summary */}
                <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
                    <Card className="bg-purple-50 border-purple-100">
                        <CardHeader className="pb-2">
                            <CardTitle className="text-xs font-bold text-purple-800 uppercase">AI Traces Today</CardTitle>
                        </CardHeader>
                        <CardContent>
                            <div className="text-2xl font-bold text-purple-900">124</div>
                        </CardContent>
                    </Card>
                    <Card className="bg-green-50 border-green-100">
                        <CardHeader className="pb-2">
                            <CardTitle className="text-xs font-bold text-green-800 uppercase">Auto-Resolved</CardTitle>
                        </CardHeader>
                        <CardContent>
                            <div className="text-2xl font-bold text-green-900">92%</div>
                        </CardContent>
                    </Card>
                    <Card className="bg-orange-50 border-orange-100">
                        <CardHeader className="pb-2">
                            <CardTitle className="text-xs font-bold text-orange-800 uppercase">Anomalies Detected</CardTitle>
                        </CardHeader>
                        <CardContent>
                            <div className="text-2xl font-bold text-orange-900">{insights.length}</div>
                        </CardContent>
                    </Card>
                    <Card className="bg-blue-50 border-blue-100">
                        <CardHeader className="pb-2">
                            <CardTitle className="text-xs font-bold text-blue-800 uppercase">Insights Generated</CardTitle>
                        </CardHeader>
                        <CardContent>
                            <div className="text-2xl font-bold text-blue-900">{insights.length > 0 ? "Active" : "Stable"}</div>
                        </CardContent>
                    </Card>
                </div>

                {/* Main Content */}
                <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
                    <div className="lg:col-span-2">
                        <Card className="shadow-sm overflow-hidden border-t-4 border-t-purple-500">
                            <CardHeader className="flex flex-row items-center justify-between pb-6">
                                <div>
                                    <CardTitle className="flex items-center gap-2">
                                        <History className="h-5 w-5 text-muted-foreground" />
                                        Recent Accounting Traces
                                    </CardTitle>
                                    <CardDescription>Click any row to drill into the AI's step-by-step logic.</CardDescription>
                                </div>
                                <div className="relative w-64">
                                    <Search className="absolute left-2.5 top-2.5 h-4 w-4 text-muted-foreground" />
                                    <Input
                                        placeholder="Search by ID or Entity..."
                                        className="pl-9 h-9"
                                        value={searchQuery}
                                        onChange={(e) => setSearchQuery(e.target.value)}
                                    />
                                </div>
                            </CardHeader>
                            <CardContent className="p-0">
                                <Table>
                                    <TableHeader className="bg-muted/30">
                                        <TableRow>
                                            <TableHead className="font-bold">Entity Reference</TableHead>
                                            <TableHead className="font-bold">Transaction Type</TableHead>
                                            <TableHead className="font-bold">Time</TableHead>
                                            <TableHead className="font-bold">AI Confidence</TableHead>
                                            <TableHead className="font-bold">Status</TableHead>
                                            <TableHead className="text-right"></TableHead>
                                        </TableRow>
                                    </TableHeader>
                                    <TableBody>
                                        {isLoading ? (
                                            <TableRow>
                                                <TableCell colSpan={6} className="text-center py-20">
                                                    <Loader2 className="h-8 w-8 animate-spin mx-auto text-primary" />
                                                    <p className="text-xs text-muted-foreground mt-2">Loading intelligence data...</p>
                                                </TableCell>
                                            </TableRow>
                                        ) : (
                                            recentTraces?.map((trace: any) => (
                                                <TableRow
                                                    key={trace.id}
                                                    className="cursor-pointer hover:bg-purple-50/30 transition-colors group"
                                                    onClick={() => handleViewTrace({ entityId: trace.entityId, entityTable: trace.entityTable })} role="button" tabIndex={0} onKeyDown={(e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); e.currentTarget.click(); } }}
                                                >
                                                    <TableCell className="font-mono text-sm font-medium">{trace.entityId}</TableCell>
                                                    <TableCell><Badge variant="outline" className="text-[10px]">{trace.entityTable}</Badge></TableCell>
                                                    <TableCell className="text-xs text-muted-foreground">{format(new Date(trace.date), 'h:mm a')}</TableCell>
                                                    <TableCell>
                                                        <div className="flex items-center gap-2">
                                                            <div className="flex-1 h-1.5 w-16 bg-muted rounded-full overflow-hidden">
                                                                <div
                                                                    className={`h-full bg-purple-500 transition-all duration-500 ${trace.confidence > 0.9 ? 'w-[95%]' :
                                                                        trace.confidence > 0.8 ? 'w-[85%]' :
                                                                            trace.confidence > 0.6 ? 'w-[70%]' : 'w-[50%]'
                                                                        }`}
                                                                ></div>
                                                            </div>
                                                            <span className="text-xs font-bold">{(trace.confidence * 100).toFixed(0)}%</span>
                                                        </div>
                                                    </TableCell>
                                                    <TableCell>
                                                        {trace.status === 'SUCCESS' ? (
                                                            <div className="flex items-center gap-1.5 text-green-600 text-[10px] font-bold">
                                                                <CheckCircle2 className="h-3 w-3" /> VERIFIED
                                                            </div>
                                                        ) : (
                                                            <div className="flex items-center gap-1.5 text-orange-600 text-[10px] font-bold">
                                                                <AlertCircle className="h-3 w-3" /> ANOMALY
                                                            </div>
                                                        )}
                                                    </TableCell>
                                                    <TableCell className="text-right">
                                                        <Button variant="ghost" size="icon" className="group-hover:text-purple-600">
                                                            <Eye className="h-4 w-4" />
                                                        </Button>
                                                    </TableCell>
                                                </TableRow>
                                            ))
                                        )}
                                    </TableBody>
                                </Table>
                            </CardContent>
                        </Card>
                    </div>

                    <div className="space-y-6">
                        <Card className="bg-purple-900 text-white border-purple-800 shadow-lg">
                            <CardHeader>
                                <CardTitle className="text-lg flex items-center gap-2">
                                    <Sparkles className="h-5 w-5" /> Proactive Insights
                                </CardTitle>
                                <CardDescription className="text-purple-200">AI recommendations for your ruleset.</CardDescription>
                            </CardHeader>
                            <CardContent className="space-y-4">
                                {insights.map((insight: any, idx: number) => (
                                    <div key={idx} className="bg-white/10 p-3 rounded-lg border border-white/20">
                                        <div className="flex justify-between items-start mb-1">
                                            <h4 className="text-xs font-bold uppercase text-purple-200">{insight.title}</h4>
                                            <Badge className={insight.severity === 'HIGH' ? 'bg-red-500' : 'bg-orange-500'}>
                                                {insight.severity}
                                            </Badge>
                                        </div>
                                        <p className="text-xs mb-2 opacity-90">{insight.description}</p>
                                        <div className="flex gap-2">
                                            <Button
                                                size="sm"
                                                variant="secondary"
                                                className="h-7 text-[10px] bg-white text-purple-900 hover:bg-purple-50"
                                                onClick={() => handleApplyInsight(insight)}
                                            >
                                                {insight.actionLabel}
                                            </Button>
                                        </div>
                                    </div>
                                ))}
                                {insights.length === 0 && (
                                    <div className="text-center py-6 text-purple-300 italic text-xs">
                                        No active suggestions. Accounting engine is performing optimally.
                                    </div>
                                )}
                                <Button
                                    variant="outline"
                                    className="w-full border-purple-400 text-purple-100 hover:bg-purple-800 transition-colors"
                                    onClick={() => refetchInsights()}
                                >
                                    Force Analysis
                                </Button>
                            </CardContent>
                        </Card>

                        <Card>
                            <CardHeader>
                                <CardTitle className="text-sm font-bold uppercase tracking-wider text-muted-foreground">Trace New Transaction</CardTitle>
                            </CardHeader>
                            <CardContent className="space-y-4">
                                <div className="space-y-2">
                                    <Input placeholder="Enter Transaction ID..." className="h-9" />
                                    <Button className="w-full gap-2 transition-transform hover:scale-[1.02]">
                                        <Sparkles className="h-4 w-4" /> Generate Logic Trace
                                    </Button>
                                </div>
                                <p className="text-[10px] text-muted-foreground leading-relaxed italic">
                                    Trace generation performs a dry-run of the rule engine and provides step-by-step account derivation details.
                                </p>
                            </CardContent>
                        </Card>
                    </div>
                </div>
            </div>

            {/* Trace Modal */}
            <AccountingTraceModal
                open={!!selectedTrace}
                onOpenChange={(open) => !open && setSelectedTrace(null)}
                trace={selectedTraceData}
                isLoading={isTraceLoading}
            />
        </StandardPage>
    );
}
